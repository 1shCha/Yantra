    await new Promise((resolve) => setTimeout(resolve, 100));
    await fs.writeFile(path.join(root, 'canvas-narrow.png'), (await window.webContents.capturePage()).toPNG());
    assert.equal(await evaluate(`document.documentElement.scrollWidth > innerWidth`), false);
    // Protected title behavior uses the same editor in nodes and documents.
    const editorAction = (script: string) => evaluate(`(() => { const editor = document.querySelector('[contenteditable=true]').editor; ${script} })()`);
