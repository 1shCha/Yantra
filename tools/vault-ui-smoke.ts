    await waitFor(`!!document.querySelector('.react-flow__pane')`);
    await contextMenu(trashCanvas.path);
    await click('Move to Trash');
    await waitFor(`!document.querySelector('.vault-dialog[open]') && !document.querySelector('.react-flow__pane')`);
