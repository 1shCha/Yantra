    await waitFor(`document.querySelector('[aria-label="Bold"]').matches(':disabled')`);
    assert.equal(await editorAction(`return editor.state.doc.firstChild.type.name === 'heading' && editor.state.doc.firstChild.attrs.level === 1;`), true);
    await editorAction(`editor.commands.selectAll(); editor.commands.insertContent('A long title with English words that wraps across several lines in the canvas node'); editor.commands.setTextSelection(8);`);
    await waitFor(`document.querySelector('.markdown-node__prose h1')?.textContent === 'A long title with English words that wraps across several lines in the canvas node'`);
    await waitFor(`document.querySelector('[aria-label="Bold"]').matches(':disabled')`);
    assert.equal(await evaluate(`(() => { const title = document.querySelector('.markdown-node__prose h1'); return title.getBoundingClientRect().height > parseFloat(getComputedStyle(title).lineHeight) * 1.5; })()`), true);
    await evaluate(`new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)))`);
    await fs.writeFile(path.join(root, 'protected-title-node.png'), (await window.webContents.capturePage()).toPNG());
    await window.webContents.insertText('123!');
    await waitFor(`!!document.querySelector('.document-title-error')`);
    assert.equal(await editorAction(`return editor.state.doc.firstChild.textContent.includes('123!');`), false);
    for (const type of ['keyDown', 'char', 'keyUp'] as const) window.webContents.sendInputEvent({ type, keyCode: 'Enter' });
    await waitFor(`!!document.querySelector('[contenteditable=true]') && !document.querySelector('[inert].vault-live-canvas') && !document.querySelector('[aria-label="Bold"]').matches(':disabled')`);
    await waitFor(`document.activeElement === document.querySelector('[contenteditable=true]')`);
    nodeDocumentPath = path.join(vaultPath, 'Unfiled', 'A_long_title_with_English_words_that_wraps_across_several_lines_in_the_canvas_node.yantraD');
    await fs.stat(nodeDocumentPath);
    await assert.rejects(fs.stat(path.join(vaultPath, 'Unfiled', 'Untitled.yantraD')), { code: 'ENOENT' });
    assert.equal(await editorAction(`return editor.state.doc.firstChild.textContent;`), 'A long title with English words that wraps across several lines in the canvas node');
