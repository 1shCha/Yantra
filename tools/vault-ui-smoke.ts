    await click('Bold');
    assert.equal(await editorAction(`return editor.state.doc.child(1).firstChild.marks.some(mark => mark.type.name === 'bold');`), true);
    await click('Open Document');
    await waitFor(`!document.querySelector('.react-flow') && !!document.querySelector('[contenteditable=true]')`);
